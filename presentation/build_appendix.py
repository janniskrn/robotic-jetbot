"""Writes the full source of the driving program into the appendix of the presentation.

    python presentation/build_appendix.py [index_v3.html]

The slides show excerpts with line numbers; the appendix shows the whole files with the same numbers,
so every excerpt can be looked up. It is generated, never pasted: a hand-copied listing is stale within
a week, and `check.py` fails when the appendix no longer matches the files.

The appendix is in the document view only (`d`), which is also what the PDF for the weekly upload prints.
"""

import io
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SOURCE_DIR = os.path.join(os.path.dirname(HERE), 'notebooks', 'mini_av')

# the files that run while the robot drives, in the order of the pipeline
FILES = ['drive.py', 'perception.py', 'decision.py', 'control.py', 'config.py', 'safety.py']

START = '<!-- APPENDIX START, generated by build_appendix.py: do not edit by hand -->'
END = '<!-- APPENDIX END -->'


def escape(text):
    return text.replace('&', '&amp;').replace('<', '&lt;').replace('>', '&gt;')


def listing(name):
    lines = io.open(os.path.join(SOURCE_DIR, name), encoding='utf-8').read().split('\n')
    while lines and not lines[-1].strip():
        lines.pop()
    body = '\n'.join('<span class="ln">%d</span>%s' % (i + 1, escape(line))
                     for i, line in enumerate(lines))
    return ('<div class="srcfile">\n  <h3>%s <span class="fn">%d lines</span></h3>\n<pre>%s</pre>\n</div>'
            % (name, len(lines), body))


def main():
    page_path = os.path.join(HERE, sys.argv[1] if len(sys.argv) > 1 else 'index_v3.html')
    page = io.open(page_path, encoding='utf-8').read()
    appendix = '\n'.join([
        START,
        '<div class="appendix doconly">',
        '  <h2>Appendix: the full driving program</h2>',
        '  <p>Every file that runs while the robot drives, complete, with the line numbers the slides cite.',
        '  %d lines of the 2703 we wrote. The rest (recording, labeling, training, the test scripts) is in the'
        ' repository under <span class="path">notebooks/mini_av/</span>.</p>' % sum(
            len(io.open(os.path.join(SOURCE_DIR, f), encoding='utf-8').read().rstrip('\n').split('\n'))
            for f in FILES),
        '\n'.join(listing(name) for name in FILES),
        '</div>',
        END,
    ])

    if START in page:
        head, rest = page.split(START, 1)
        page = head + appendix + rest.split(END, 1)[1]
    else:
        page = page.replace('</div>\n\n<script>', '</div>\n\n' + appendix + '\n\n<script>', 1)
    io.open(page_path, 'w', encoding='utf-8', newline='').write(page)
    print('appendix: %d files, %d bytes' % (len(FILES), len(appendix)))


if __name__ == '__main__':
    main()
